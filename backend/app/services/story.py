"""Period "story": a deterministic, evidence-tagged text summary of what the dataset shows for one region and period.

Nothing here is generated by an AI service. Every sentence is built from numbers computed from the loaded rows, and each
carries the evidence it is based on. Causes are never asserted: the "why" section only reports other variables that
co-vary in the dataset and says plainly when the dataset cannot establish a cause.
"""

from __future__ import annotations

import calendar
import math

import numpy as np
import pandas as pd
from scipy import stats as sps

from app.errors import not_found, unprocessable
from app.schemas_story import (
    CoVarying,
    ExtremePoint,
    GeoInfo,
    MonthPoint,
    PeriodInfo,
    RegionOption,
    RegionsResponse,
    StoryRequest,
    StoryResponse,
    StorySentence,
    StoryStats,
    WhySection,
)
from app.services.places import PLACES_NOTE, region_centre
from app.services.provenance import build_provenance
from app.services.store import DatasetRecord

SYNTHETIC_BANNER = "SYNTHETIC DEMO — NOT NASA OBSERVATIONS"

# Approximate display extents (west, south, east, north) used ONLY to place the 3D camera for well-known demo region
# names when the dataset has no coordinates. They are not dataset values and no statistic depends on them.
APPROX_EXTENTS: dict[str, tuple[float, float, float, float]] = {
    "india": (68.0, 6.5, 97.5, 37.0),
    "amazon": (-74.0, -16.0, -48.0, 5.0),
    "central africa": (9.0, -13.0, 32.0, 8.0),
}
UNDRIVEN_NAME_HINTS = ("error", "uncertain", "quality", "flag", "count", "weight")
MIN_CLIMATOLOGY_YEARS = 3


def _month_label(ts: pd.Timestamp) -> str:
    return f"{calendar.month_name[ts.month]} {ts.year}"


def period_label(start: pd.Timestamp, end: pd.Timestamp) -> str:
    if start.year == end.year and start.month == end.month:
        return _month_label(start)
    if start.year == end.year:
        return f"{calendar.month_abbr[start.month]}–{calendar.month_abbr[end.month]} {start.year}"
    return f"{calendar.month_abbr[start.month]} {start.year} – {calendar.month_abbr[end.month]} {end.year}"


def geo_for(record: DatasetRecord, region: str) -> GeoInfo:
    df = record.data
    grid = record.extra.get("grid")
    if grid is not None:
        b = grid.bbox
        return GeoInfo(
            kind="dataset_coordinates",
            bbox=b,
            center=((b[0] + b[2]) / 2, (b[1] + b[3]) / 2),
            note="Extent and per-cell values come from the uploaded grid; the summary statistics are area-weighted means over its valid cells.",
        )
    if "latitude" in df.columns and "longitude" in df.columns:
        pts = df.loc[df["region"] == region, ["latitude", "longitude"]].dropna()
        if len(pts):
            lat0, lat1 = float(pts["latitude"].min()), float(pts["latitude"].max())
            lon0, lon1 = float(pts["longitude"].min()), float(pts["longitude"].max())
            pad = 0.5
            return GeoInfo(
                kind="dataset_coordinates",
                bbox=(lon0 - pad, lat0 - pad, lon1 + pad, lat1 + pad),
                center=((lon0 + lon1) / 2, (lat0 + lat1) / 2),
                note="Extent taken from the dataset's own latitude/longitude columns.",
            )
    centre = region_centre(region)
    if centre is not None:
        lon, lat = centre
        return GeoInfo(
            kind="approximate_extent",
            bbox=(lon - 1.5, lat - 1.5, lon + 1.5, lat + 1.5),
            center=(lon, lat),
            note="Approximate location: a small box around the region's centre from a reference table. It is not the region's boundary, and the colour describes the whole region. " + PLACES_NOTE,
        )
    ext = APPROX_EXTENTS.get(region.strip().lower())
    if ext is not None:
        return GeoInfo(
            kind="approximate_extent",
            bbox=ext,
            center=((ext[0] + ext[2]) / 2, (ext[1] + ext[3]) / 2),
            note="Approximate display extent for placing the map. The dataset provides one value per region per month, not a per-place grid, so colours describe the whole region.",
        )
    return GeoInfo(kind="none", note="No coordinates are available for this region, so it cannot be located on the map.")


def default_variable(record: DatasetRecord) -> str | None:
    names = sorted(record.data["variable"].dropna().unique().tolist())
    for n in names:
        if not any(h in n.lower() for h in UNDRIVEN_NAME_HINTS):
            return n
    return names[0] if names else None


def list_regions(record: DatasetRecord) -> RegionsResponse:
    df = record.data
    out = []
    for name, g in df.groupby("region", sort=True):
        out.append(
            RegionOption(
                region=name,
                variables=sorted(g["variable"].unique().tolist()),
                start=None if pd.isna(g["date"].min()) else g["date"].min().date(),
                end=None if pd.isna(g["date"].max()) else g["date"].max().date(),
                geo=geo_for(record, name),
            )
        )
    return RegionsResponse(
        provenance=build_provenance(record), dataset_id=record.id, default_variable=default_variable(record), regions=out
    )


def _f(x) -> float | None:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def _fmt(x: float, unit: str) -> str:
    ax = abs(x)
    s = f"{x:.2e}" if (ax and (ax < 0.001 or ax >= 1e5)) else f"{x:.3f}".rstrip("0").rstrip(".")
    return f"{s} {unit}".strip()


def _ext(df: pd.DataFrame, idx) -> ExtremePoint:
    row = df.loc[idx]
    return ExtremePoint(date=row["date"].date(), value=float(row["value"]))


def _climatology(series: pd.DataFrame) -> tuple[dict[int, tuple[float, float, int]], bool]:
    """month -> (mean, std, n) over the whole series; second value says whether it is reliable enough to use."""
    out: dict[int, tuple[float, float, int]] = {}
    ok = True
    for m, g in series.groupby(series["date"].dt.month):
        v = g["value"].dropna().to_numpy(dtype=float)
        if len(v) < MIN_CLIMATOLOGY_YEARS:
            ok = False
        out[int(m)] = (float(v.mean()) if len(v) else float("nan"), float(v.std(ddof=1)) if len(v) > 1 else float("nan"), len(v))
    return out, ok and len(out) == 12


def _co_varying(record: DatasetRecord, variable: str, region: str, period_months: pd.DatetimeIndex, target: pd.Series) -> list[CoVarying]:
    """Other variables for the same region whose monthly values rise and fall with the target inside the period."""
    out: list[CoVarying] = []
    df = record.data
    for other in sorted(df["variable"].unique()):
        if other == variable or any(h in other.lower() for h in UNDRIVEN_NAME_HINTS):
            continue
        sub = df[(df["variable"] == other) & (df["region"] == region)].set_index("date")["value"]
        sub = sub[~sub.index.duplicated()].reindex(period_months)
        joined = pd.concat([target.reindex(period_months), sub], axis=1, keys=["a", "b"]).dropna()
        if len(joined) >= 6 and joined["a"].nunique() > 1 and joined["b"].nunique() > 1:
            rho, _ = sps.spearmanr(joined["a"], joined["b"])
            if math.isfinite(rho):
                out.append(CoVarying(variable=other, spearman_rho=float(rho), n=int(len(joined))))
    return sorted(out, key=lambda c: -abs(c.spearman_rho))


def build_story(record: DatasetRecord, req: StoryRequest) -> StoryResponse:
    variable = req.variable or default_variable(record)
    if variable is None:
        raise unprocessable("empty_dataset", "This dataset has no variables.")
    df = record.data
    var_rows = df[df["variable"] == variable]
    if var_rows.empty:
        raise not_found("variable_not_found", f"Variable '{variable}' does not exist in dataset '{record.name}'.")
    series_all = var_rows[var_rows["region"] == req.region].sort_values("date")
    if series_all.empty:
        raise not_found("series_not_found", f"Region '{req.region}' has no data for variable '{variable}' in this dataset.")
    if req.start > req.end:
        raise unprocessable("invalid_date_range", "The start date must not be after the end date.")

    unit = ", ".join(sorted(series_all["unit"].dropna().unique().tolist())) or ""
    p_start = pd.Timestamp(req.start).to_period("M").to_timestamp()
    p_end = pd.Timestamp(req.end).to_period("M").to_timestamp()
    data_first, data_last = series_all["date"].min(), series_all["date"].max()
    prov = build_provenance(record, series_all)
    banner = SYNTHETIC_BANNER if prov.is_synthetic else None
    geo = geo_for(record, req.region)

    expected = pd.date_range(p_start, p_end, freq="MS")
    # Monthly values (one per month start). Duplicated months are averaged only for this view, never written back.
    monthly = series_all.assign(m=series_all["date"].dt.to_period("M").dt.to_timestamp()).groupby("m")["value"].mean()
    clim, clim_ok = _climatology(series_all)

    months: list[MonthPoint] = []
    for ts in expected:
        v = _f(monthly.get(ts, np.nan))
        c = clim.get(ts.month)
        cm = _f(c[0]) if (c and clim_ok) else None
        csd = _f(c[1]) if (c and clim_ok) else None
        anom = (v - cm) if (v is not None and cm is not None) else None
        z = (anom / csd) if (anom is not None and csd not in (None, 0.0)) else None
        months.append(
            MonthPoint(date=ts.date(), value=v, climatology=cm, anomaly=anom, anomaly_z=z, unusual=bool(z is not None and abs(z) >= 2.0))
        )
    valid = [m for m in months if m.value is not None]
    period = PeriodInfo(
        start=p_start.date(),
        end=p_end.date(),
        label=period_label(p_start, p_end),
        n_months_expected=len(expected),
        n_valid=len(valid),
        n_missing=len(expected) - len(valid),
    )

    caveats: list[str] = []
    if banner:
        caveats.append(f"{banner}. These numbers are invented demo values and do not describe real conditions.")
    if p_end < data_first.to_period("M").to_timestamp() or p_start > data_last.to_period("M").to_timestamp():
        raise unprocessable(
            "period_outside_data",
            f"The dataset covers {_month_label(data_first)} to {_month_label(data_last)} for this region; nothing falls in {period.label}.",
        )
    if not valid:
        raise unprocessable("no_rows_in_range", f"No valid observations for {req.region} in {period.label}.")
    if p_start < data_first.to_period("M").to_timestamp() or p_end > data_last.to_period("M").to_timestamp():
        caveats.append(f"Part of the requested period lies outside the data ({_month_label(data_first)} to {_month_label(data_last)}); only covered months are summarised.")
    if period.n_missing and period.n_missing < period.n_months_expected:
        caveats.append(f"{period.n_missing} of {period.n_months_expected} months in the period have no valid value and are left out, not filled in.")
    if not clim_ok:
        caveats.append("The series is too short to build a month-by-month normal (needs at least 3 values for each calendar month), so anomalies are not shown.")

    pdf = pd.DataFrame({"date": [pd.Timestamp(m.date) for m in valid], "value": [m.value for m in valid]})
    vals = pdf["value"].to_numpy(dtype=float)
    mean = float(vals.mean())
    imin, imax = int(pdf["value"].idxmin()), int(pdf["value"].idxmax())
    first, last = pdf.iloc[0], pdf.iloc[-1]
    change_abs = change_pct = slope = None
    if len(pdf) >= 2:
        change_abs = float(last["value"] - first["value"])
        if first["value"] not in (0, 0.0):
            change_pct = float(change_abs / abs(first["value"]) * 100)
    if len(pdf) >= 6:
        t = (pdf["date"].dt.year + (pdf["date"].dt.month - 1) / 12).to_numpy()
        slope = _f(sps.linregress(t, vals).slope)
    anomalies = [m.anomaly for m in valid if m.anomaly is not None]
    baseline = [m.climatology for m in valid if m.climatology is not None]
    base_mean = float(np.mean(baseline)) if baseline else None
    anom_mean = float(np.mean(anomalies)) if anomalies else None
    anom_pct = (anom_mean / abs(base_mean) * 100) if (anom_mean is not None and base_mean not in (None, 0.0)) else None

    prev_mean = prev_pct = None
    if len(expected) >= 1:
        n = len(expected)
        prev_range = pd.date_range(end=p_start - pd.DateOffset(months=1), periods=n, freq="MS")
        pv = [monthly.get(ts) for ts in prev_range]
        pv = [float(v) for v in pv if v is not None and math.isfinite(v)]
        if len(pv) >= max(1, int(0.8 * n)):
            prev_mean = float(np.mean(pv))
            if prev_mean != 0:
                prev_pct = (mean - prev_mean) / abs(prev_mean) * 100

    stats = StoryStats(
        unit=unit,
        mean=mean,
        minimum=ExtremePoint(date=pdf.loc[imin, "date"].date(), value=float(pdf.loc[imin, "value"])),
        maximum=ExtremePoint(date=pdf.loc[imax, "date"].date(), value=float(pdf.loc[imax, "value"])),
        first=ExtremePoint(date=first["date"].date(), value=float(first["value"])),
        last=ExtremePoint(date=last["date"].date(), value=float(last["value"])),
        change_abs=change_abs,
        change_pct=change_pct,
        descriptive_slope_per_year=slope,
        baseline_mean=base_mean,
        anomaly_mean=anom_mean,
        anomaly_pct=anom_pct,
        previous_period_mean=prev_mean,
        previous_period_change_pct=prev_pct,
    )

    s: list[StorySentence] = []
    where = f"{req.region}" + (" (synthetic demo)" if banner else "")
    single = len(valid) == 1
    if single:
        s.append(StorySentence(kind="observation", text=f"{period.label}, {where}: {variable} was {_fmt(mean, unit)}.", evidence=f"value={mean:.6g} {unit}"))
    else:
        s.append(
            StorySentence(
                kind="observation",
                text=f"Across {period.label} ({len(valid)} valid months), {variable} in {where} averaged {_fmt(mean, unit)}.",
                evidence=f"mean of {len(valid)} monthly values = {mean:.6g} {unit}",
            )
        )
        mn, mx = stats.minimum, stats.maximum
        s.append(
            StorySentence(
                kind="observation",
                text=f"The lowest month was {_month_label(pd.Timestamp(mn.date))} ({_fmt(mn.value, unit)}) and the highest was {_month_label(pd.Timestamp(mx.date))} ({_fmt(mx.value, unit)}).",
                evidence=f"min={mn.value:.6g} on {mn.date}; max={mx.value:.6g} on {mx.date}",
            )
        )
        if change_abs is not None:
            word = "rose" if change_abs > 0 else "fell" if change_abs < 0 else "did not change"
            pct = f" ({change_pct:+.1f}%)" if change_pct is not None else ""
            s.append(
                StorySentence(
                    kind="observation",
                    text=f"From {_month_label(pd.Timestamp(first['date']))} to {_month_label(pd.Timestamp(last['date']))} the value {word}{'' if word == 'did not change' else ' by ' + _fmt(abs(change_abs), unit)}{pct if word != 'did not change' else ''}. This compares two single months, so it is sensitive to the normal seasonal cycle.",
                    evidence=f"first={first['value']:.6g}, last={last['value']:.6g}",
                )
            )
    if anom_mean is not None and base_mean is not None:
        direction = "above" if anom_mean > 0 else "below" if anom_mean < 0 else "equal to"
        pct_txt = f", so {abs(anom_pct):.1f}% {'higher' if anom_mean > 0 else 'lower'}" if anom_pct is not None and anom_mean != 0 else ""
        s.append(
            StorySentence(
                kind="comparison",
                text=f"That is {_fmt(abs(anom_mean), unit)} {direction} the usual value for the same calendar month{'s' if not single else ''} in this dataset: {_fmt(base_mean, unit)}{pct_txt}.",
                evidence=f"anomaly={anom_mean:.6g}; month-by-month normal={base_mean:.6g} from the whole series",
            )
        )
        unusual = [m for m in valid if m.unusual]
        if unusual:
            names = ", ".join(_month_label(pd.Timestamp(m.date)) for m in unusual[:4]) + (" and others" if len(unusual) > 4 else "")
            s.append(
                StorySentence(
                    kind="comparison",
                    text=f"Unusual by this dataset's own spread (at least 2 standard deviations from that month's normal): {names}.",
                    evidence=f"{len(unusual)} month(s) with |z| ≥ 2",
                )
            )
    if prev_mean is not None and prev_pct is not None:
        s.append(
            StorySentence(
                kind="comparison",
                text=f"The {len(expected)} {'month' if len(expected) == 1 else 'months'} before this period averaged {_fmt(prev_mean, unit)}, so this period was {abs(prev_pct):.1f}% {'higher' if prev_pct > 0 else 'lower'}. Seasonal timing can drive part of that difference.",
                evidence=f"previous mean={prev_mean:.6g}",
            )
        )
    if slope is not None:
        s.append(
            StorySentence(
                kind="context",
                text=f"Within this period the fitted line changes by {_fmt(slope, unit + ' per year')}. This is a descriptive fit over a short window, not a significance test; use Trend analysis for tested results.",
                evidence=f"descriptive OLS slope={slope:.6g}",
            )
        )

    co = _co_varying(record, variable, req.region, expected, pd.Series({pd.Timestamp(m.date): m.value for m in valid}))
    if co:
        top = co[0]
        why = WhySection(
            cause_established=False,
            statement=(
                f"The dataset also holds {', '.join(c.variable for c in co)} for this region. Within this period {top.variable} moves with {variable} "
                f"(Spearman ρ = {top.spearman_rho:+.2f}, n = {top.n}). Co-movement is a lead worth investigating, not a cause: the dataset alone cannot show what drove the change."
            ),
            co_varying=co,
        )
        s.append(StorySentence(kind="hypothesis", text=why.statement, evidence=f"Spearman rho={top.spearman_rho:.3f}, n={top.n}"))
    else:
        why = WhySection(
            cause_established=False,
            statement=(
                f"This dataset contains only {variable} for {req.region} (no driver variables such as temperature, wind or land cover), so it cannot explain why the change happened. "
                "Add a dataset with candidate drivers to investigate causes; any cause named without such data would be a guess."
            ),
        )
        s.append(StorySentence(kind="limitation", text=why.statement, evidence="no other usable variables for this region"))
    if geo.kind != "none":
        s.append(StorySentence(kind="limitation", text=geo.note, evidence=f"geo.kind={geo.kind}"))

    return StoryResponse(
        provenance=prov,
        dataset_id=record.id,
        region=req.region,
        variable=variable,
        unit=unit,
        period=period,
        geo=geo,
        stats=stats,
        months=months,
        sentences=s,
        why=why,
        banner=banner,
        caveats=caveats,
    )

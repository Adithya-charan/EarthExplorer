"""Generate the bundled SYNTHETIC demo dataset.

Run from the ``backend`` directory::

    python scripts/generate_demo_data.py

The output (``data/earth_science_trend_demo.csv``) is entirely artificial. It is
produced from a seeded random number generator and contains NO NASA data, NO
satellite observations and NO real-world measurements. Variable and region names
are deliberately generic ("Synthetic Index A", "Region Alpha") so that nothing
can be mistaken for an Earth-science product, mission or place.

Series design (all values are artificial and exist only to exercise the app):

* Index A  - four regions, monthly 2000-01..2023-12. Alpha trends up, Beta trends
  down (opposite directions), Gamma has no trend and a 12-month block of blank
  values, Delta has a weak trend and scattered blank values.
* Index B  - three regions, monthly, strong seasonality.
* Index C  - deliberately heterogeneous: Alpha monthly, Beta monthly but shorter
  coverage, Gamma annual. Used to exercise comparability warnings.
"""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

SEED = 20260101
DATA_SOURCE = "Synthetic demo data (generated by backend/scripts/generate_demo_data.py)"
OUT = Path(__file__).resolve().parent.parent / "data" / "earth_science_trend_demo.csv"


def ar1_noise(rng: np.random.Generator, n: int, phi: float, sigma: float) -> np.ndarray:
    eps = rng.normal(0.0, sigma, n)
    out = np.zeros(n)
    out[0] = eps[0]
    for i in range(1, n):
        out[i] = phi * out[i - 1] + eps[i]
    return out


def monthly_series(
    rng: np.random.Generator,
    start_year: int,
    end_year: int,
    base: float,
    slope_per_year: float,
    seasonal_amp: float,
    phi: float,
    sigma: float,
    phase: float = 0.0,
) -> tuple[list[str], np.ndarray]:
    dates = [f"{y}-{m:02d}-01" for y in range(start_year, end_year + 1) for m in range(1, 13)]
    n = len(dates)
    t_years = np.arange(n) / 12.0
    months = np.arange(n) % 12
    seasonal = seasonal_amp * np.sin(2 * np.pi * months / 12.0 + phase)
    values = base + slope_per_year * t_years + seasonal + ar1_noise(rng, n, phi, sigma)
    return dates, values


def build_rows() -> list[dict[str, object]]:
    rng = np.random.default_rng(SEED)
    rows: list[dict[str, object]] = []

    def add(dates, values, region, variable, unit, blank_idx=()):
        blank = set(blank_idx)
        for i, (d, v) in enumerate(zip(dates, values)):
            rows.append(
                {
                    "date": d,
                    "region": region,
                    "variable": variable,
                    "value": "" if i in blank else f"{v:.4f}",
                    "unit": unit,
                    "data_source": DATA_SOURCE,
                    "is_synthetic": "true",
                }
            )

    # --- Synthetic Index A -------------------------------------------------
    unit_a = "synthetic unit A"
    d, v = monthly_series(rng, 2000, 2023, 10.0, +0.060, 2.0, 0.35, 0.60)
    add(d, v, "Region Alpha", "Synthetic Index A", unit_a)
    d, v = monthly_series(rng, 2000, 2023, 12.0, -0.050, 1.5, 0.30, 0.60, phase=0.8)
    add(d, v, "Region Beta", "Synthetic Index A", unit_a)
    d, v = monthly_series(rng, 2000, 2023, 11.0, 0.000, 1.0, 0.30, 0.80, phase=1.6)
    add(d, v, "Region Gamma", "Synthetic Index A", unit_a, blank_idx=range(137, 149))
    d, v = monthly_series(rng, 2000, 2023, 9.0, +0.004, 1.2, 0.40, 1.00, phase=2.4)
    blanks = sorted(rng.choice(len(d), size=14, replace=False).tolist())
    add(d, v, "Region Delta", "Synthetic Index A", unit_a, blank_idx=blanks)

    # --- Synthetic Index B (strong seasonality) ----------------------------
    unit_b = "synthetic unit B"
    d, v = monthly_series(rng, 2000, 2023, 50.0, +0.120, 8.0, 0.25, 1.50)
    add(d, v, "Region Alpha", "Synthetic Index B", unit_b)
    d, v = monthly_series(rng, 2000, 2023, 55.0, -0.100, 6.0, 0.25, 1.50, phase=0.5)
    add(d, v, "Region Beta", "Synthetic Index B", unit_b)
    d, v = monthly_series(rng, 2000, 2023, 52.0, 0.000, 7.0, 0.25, 1.50, phase=1.0)
    add(d, v, "Region Gamma", "Synthetic Index B", unit_b)

    # --- Synthetic Index C (heterogeneous coverage / resolution) ----------
    unit_c = "synthetic unit C"
    d, v = monthly_series(rng, 2000, 2023, 100.0, +0.300, 3.0, 0.40, 2.00)
    add(d, v, "Region Alpha", "Synthetic Index C", unit_c)
    d, v = monthly_series(rng, 2008, 2023, 105.0, -0.250, 3.0, 0.40, 2.00, phase=0.7)
    add(d, v, "Region Beta", "Synthetic Index C", unit_c)
    years = list(range(2000, 2024))
    annual = 98.0 + 0.1 * np.arange(len(years)) + rng.normal(0, 2.0, len(years))
    add([f"{y}-01-01" for y in years], annual, "Region Gamma", "Synthetic Index C", unit_c)

    return rows


def main() -> None:
    rows = build_rows()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fields = ["date", "region", "variable", "value", "unit", "data_source", "is_synthetic"]
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {len(rows)} SYNTHETIC rows to {OUT}")


if __name__ == "__main__":
    main()

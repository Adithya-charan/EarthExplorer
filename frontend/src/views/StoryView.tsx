interface Req {
  region: string;
  start: string; // YYYY-MM
  end: string; // YYYY-MM
}

const KIND_LABEL: Record<string, string> = {
  observation: "In the data",
  comparison: "Compared",
  context: "Context",
  limitation: "Limit",
  hypothesis: "Lead, not a cause",
};

export function storyToMarkdown(s: StoryResponse): string {
  const p = s.provenance;
  const lines = [
    `# ${s.region}, ${s.period.label}`,
    s.banner ? `\n**${s.banner}**\n` : "",
    `Dataset: ${p.dataset_name} | status: ${p.status} | is_synthetic: ${p.is_synthetic} | dataset_sha256: ${p.dataset_checksum ?? "n/a"} | generated_at: ${p.generated_at ?? "n/a"}`,
    "",
    ...s.sentences.map((x) => `- [${KIND_LABEL[x.kind]}] ${x.text}  \n  _evidence: ${x.evidence}_`),
    "",
    ...(s.caveats.length ? ["## Caveats", ...s.caveats.map((c) => `- ${c}`), ""] : []),
    "Generated by rules from the computed statistics; no external AI service was used.",
  ];
  return lines.join("\n") + "\n";
}

function MonthBars({ story, index, onPick }: { story: StoryResponse; index: number; onPick: (i: number) => void }) {
  const months = story.months;
  const max = Math.max(1e-12, ...months.map((m) => Math.abs(m.anomaly ?? 0)));
  const hasAnom = months.some((m) => m.anomaly !== null);
  return (
    <div>
      <p className="mb-1 text-xs text-muted">
        {hasAnom ? "Difference from the usual value for each month (bars up = above usual)." : "Monthly values."} Click a bar to jump to that month.
      </p>
      <div className="flex h-24 items-center gap-px" role="group" aria-label="Monthly difference from usual">
        {months.map((m, i) => {
          const v = hasAnom ? m.anomaly : m.value;
          const h = v === null ? 0 : (Math.abs(v) / (hasAnom ? max : Math.max(...months.map((x) => x.value ?? 0), 1e-12))) * 44;
          return (
            <button
              key={m.date}
              type="button"
              onClick={() => onPick(i)}
              title={`${monthLabel(m.date)}: ${m.value === null ? "no value" : m.value.toPrecision(3) + " " + story.unit}${m.unusual ? " (unusual)" : ""}`}
              aria-label={`${monthLabel(m.date)}${m.value === null ? ", no value" : ""}`}
              aria-pressed={i === index}
              className="relative flex h-full min-w-px flex-1 items-center"
            >
              <span
                className="absolute left-0 right-0"
                style={{
                  height: `${Math.max(h, v === null ? 0 : 1)}%`,
                  bottom: hasAnom && (v ?? 0) < 0 ? undefined : "50%",
                  top: hasAnom && (v ?? 0) < 0 ? "50%" : undefined,
                  background: v === null ? "transparent" : hasAnom ? ((v ?? 0) >= 0 ? WET : DRY) : WET,
                  outline: i === index ? "2px solid #111" : undefined,
                  opacity: m.unusual || i === index ? 1 : 0.75,
                }}
              />
            </button>
          );
        })}
      </div>
    </div>
  );
}

function StoryBody({ datasetId }: { datasetId: string }) {
  const regions = useApi((s) => api.regions(datasetId, s), `regions:${datasetId}`);
  const boundariesApi = useApi((s) => api.boundaries({ simplify: 0.5 }, s), "boundaries");
  const [committed, setReq] = useState<Req | null>(null);
  const [edited, setDraft] = useState<Req | null>(null);
  // The cursor belongs to the story it was set for, so a new story starts again at the first month without an effect.
  const [cursor, setCursor] = useState<{ owner: unknown; i: number; playing: boolean }>({ owner: null, i: 0, playing: false });

  // Sensible defaults once the regions are known: the first region and its last three years.
  const firstRegion = regions.data?.regions[0];
  const defaults = useMemo<Req | null>(() => {
    const end = (firstRegion?.end ?? "").slice(0, 7);
    if (!firstRegion || !end) return null;
    const [y, m] = end.split("-").map(Number);
    const startYear = Math.max(Number((firstRegion.start ?? end).slice(0, 4)), y - 3);
    return { region: firstRegion.region, start: `${startYear}-${String(m).padStart(2, "0")}`, end };
  }, [firstRegion]);
  const draft = edited ?? defaults;
  const req = committed ?? defaults;

  const story = useApi(
    req ? (s) => api.story({ dataset_id: datasetId, region: req.region, variable: regions.data?.default_variable ?? undefined, start: `${req.start}-01`, end: `${req.end}-01` }, s) : null,
    req ? `story:${datasetId}:${req.region}:${req.start}:${req.end}` : "",
  );
  const data = story.data;

  const own = cursor.owner === data;
  const index = own ? cursor.i : 0;
  const playing = own && cursor.playing;
  const setIndex = (i: number) => setCursor({ owner: data, i, playing: false });
  const setPlaying = (fn: (p: boolean) => boolean) => setCursor((c) => ({ owner: data, i: c.owner === data ? c.i : 0, playing: fn(c.owner === data && c.playing) }));
  useEffect(() => {
    if (!playing || !data) return;
    const id = setInterval(
      () =>
        setCursor((c) => {
          const next = c.i + 1;
          return next >= data.months.length ? { ...c, playing: false } : { ...c, i: next };
        }),
      700,
    );
    return () => clearInterval(id);
  }, [playing, data]);

  function onChat(a: ChatAction) {
    if (a.type !== "show_story" || !a.region || !a.start || !a.end) return;
    const d = { region: a.region, start: a.start.slice(0, 7), end: a.end.slice(0, 7) };
    setDraft(d);
    setReq(d);
  }

  function pickPeriod(start: string, end: string) {
    if (!req) return;
    const d = { region: req.region, start, end };
    setDraft(d);
    setReq(d);
    document.getElementById("story-top")?.scrollIntoView?.({ behavior: "smooth", block: "start" });
  }
  function pickRegion(name: string) {
    const r = regions.data?.regions.find((x) => x.region === name);
    const end = (r?.end ?? "").slice(0, 7);
    if (!r || !end) return;
    const [y, m] = end.split("-").map(Number);
    const startYear = Math.max(Number((r.start ?? end).slice(0, 4)), y - 3);
    const d = { region: name, start: `${startYear}-${String(m).padStart(2, "0")}`, end };
    setDraft(d);
    setReq(d);
  }

  const region = regions.data?.regions.find((r) => r.region === draft?.region);
  const minMonth = region?.start?.slice(0, 7);
  const maxMonth = region?.end?.slice(0, 7);
  const boundaries = useMemo(() => (boundariesApi.data as unknown as GeoJSONFeatureCollection | undefined) ?? null, [boundariesApi.data]);
  const gridMonth = data?.months[Math.min(index, (data?.months.length ?? 1) - 1)]?.date;
  const gridCall = data && data.geo.kind === "dataset_coordinates" && gridMonth ? gridMonth : null;
  const grid = useApi(gridCall ? (s) => api.gridFrame(datasetId, gridCall, s) : null, gridCall ? `grid:${datasetId}:${gridCall}` : "");
  const current = data?.months[Math.min(index, (data?.months.length ?? 1) - 1)];

  if (regions.loading) return <LoadingState label="Loading regions" variant="cards" />;
  if (regions.error) return <ErrorState title="Could not load regions" error={regions.error} onRetry={regions.reload} />;
  if (!regions.data || !draft) return null;

  return (
    <div className="space-y-4">
      {req ? <Chronicle datasetId={datasetId} region={req.region} boundaries={boundaries} onPickPeriod={pickPeriod} onPickRegion={pickRegion} /> : null}
      <div id="story-top" className="grid scroll-mt-4 gap-4 lg:grid-cols-[minmax(0,2fr)_minmax(0,3fr)]">
        <div className="space-y-4">
          <Card>
            <CardHeader title="1. Choose a place and a time" subtitle="Pick a region, then the months you want explained." />
            <CardBody>
              <form
                className="grid gap-3 sm:grid-cols-3"
                onSubmit={(e) => {
                  e.preventDefault();
                  setReq(draft);
                }}
              >
                <label className="text-sm sm:col-span-3">
                  <span className="mb-1 block font-medium text-ink">Region</span>
                  <select
                    value={draft.region}
                    onChange={(e) => setDraft({ ...draft, region: e.target.value })}
                    className="min-h-9 w-full rounded-md border border-line bg-surface px-2"
                  >
                    {regions.data.regions.map((r) => (
                      <option key={r.region} value={r.region}>{r.region}</option>
                    ))}
                  </select>
                </label>
                <label className="text-sm">
                  <span className="mb-1 block font-medium text-ink">From (month)</span>
                  <input type="month" required min={minMonth} max={maxMonth} value={draft.start} onChange={(e) => setDraft({ ...draft, start: e.target.value })} className="min-h-9 w-full rounded-md border border-line bg-surface px-2" />
                </label>
                <label className="text-sm">
                  <span className="mb-1 block font-medium text-ink">To (month)</span>
                  <input type="month" required min={minMonth} max={maxMonth} value={draft.end} onChange={(e) => setDraft({ ...draft, end: e.target.value })} className="min-h-9 w-full rounded-md border border-line bg-surface px-2" />
                </label>
                <div className="flex items-end">
                  <Button type="submit" variant="primary" className="w-full">Show what happened</Button>
                </div>
              </form>
              {minMonth && maxMonth ? <p className="mt-2 text-xs text-muted">This region has data from {monthLabel(`${minMonth}-01`)} to {monthLabel(`${maxMonth}-01`)}.</p> : null}
            </CardBody>
          </Card>

          <Card aria-live="polite">
            <CardHeader
              title={data ? `2. What happened: ${data.region}, ${data.period.label}` : "2. What happened"}
              subtitle="Written by rules from the numbers below. Hover a sentence to see the evidence."
              actions={
                data ? (
                  <Button onClick={() => downloadText(`story_${safeFilePart(data.region)}_${safeFilePart(data.period.label)}.md`, storyToMarkdown(data), "text/markdown;charset=utf-8")}>
                    <Download size={14} aria-hidden="true" /> Report
                  </Button>
                ) : null
              }
            />
            <CardBody className="space-y-3">
              {story.loading ? <LoadingState label="Building the summary" /> : null}
              {story.error ? <ErrorState title="No summary for that choice" error={story.error} onRetry={story.reload} /> : null}
              {data ? (
                <>
                  <ProvenanceBanner provenance={data.provenance} />
                  <ul className="space-y-2" data-testid="story-sentences">
                    {data.sentences.map((s, i) => (
                      <li key={i} title={`Evidence: ${s.evidence}`} className="text-sm text-ink">
                        <Badge tone={s.kind === "limitation" ? "warn" : s.kind === "hypothesis" ? "info" : "neutral"}>{KIND_LABEL[s.kind]}</Badge>{" "}
                        {s.text}
                      </li>
                    ))}
                  </ul>
                  {data.caveats.length ? (
                    <Callout tone="warn" title="Read with care" role="note">
                      <ul className="list-disc pl-4">{data.caveats.map((c) => <li key={c}>{c}</li>)}</ul>
                    </Callout>
                  ) : null}
                </>
              ) : null}
            </CardBody>
          </Card>
        </div>

        <div className="space-y-4">
          <Card>
            <CardHeader title="3. See it on the map" subtitle="Move through time. Colour = difference from usual, column height = value." />
            <CardBody className="space-y-3">
              <div className="h-[420px]">
                {data ? (
                  <StoryMap region={data.region} geo={data.geo} months={data.months} index={index} boundaries={boundaries} banner={data.banner} frame={grid.data ?? null} />
                ) : (
                  <LoadingState label="Waiting for the summary" variant="chart" />
                )}
              </div>
              {data && data.months.length ? (
                <>
                  <div className="flex flex-wrap items-center gap-3">
                    <Button onClick={() => setPlaying((p) => !p)} aria-label={playing ? "Pause" : "Play through the months"} disabled={data.months.length < 2}>
                      {playing ? <Pause size={14} aria-hidden="true" /> : <Play size={14} aria-hidden="true" />} {playing ? "Pause" : "Play"}
                    </Button>
                    <input
                      type="range"
                      min={0}
                      max={data.months.length - 1}
                      value={Math.min(index, data.months.length - 1)}
                      onChange={(e) => setIndex(Number(e.target.value))}
                      aria-label="Month shown on the map"
                      className="min-w-40 flex-1"
                      disabled={data.months.length < 2}
                    />
                    <p className="tabular text-sm font-medium text-ink" data-testid="map-month">
                      {current ? monthLabel(current.date) : ""}
                    </p>
                  </div>
                  <p className="text-sm text-ink-soft" data-testid="map-readout">
                    {current && current.value !== null
                      ? `${current.value.toPrecision(3)} ${data.unit}` +
                        (current.anomaly !== null ? ` · ${current.anomaly >= 0 ? "+" : "−"}${Math.abs(current.anomaly).toPrecision(2)} vs usual${current.unusual ? " · unusual month" : ""}` : "")
                      : "No valid value for this month; nothing is drawn or filled in."}
                  </p>
                  <MonthBars story={data} index={index} onPick={setIndex} />
                </>
              ) : null}
            </CardBody>
          </Card>
        </div>
      </div>

      <ChatPanel
        datasetId={datasetId}
        region={draft.region}
        variable={regions.data.default_variable}
        suggestions={regions.data.regions.slice(0, 2).map((r) => `What happened in ${r.region} from ${(r.start ?? "").slice(0, 4)} to ${(r.end ?? "").slice(0, 4)}?`)}
        onAction={onChat}
      />
    </div>
  );
}

export function StoryView() {
  return (
    <div className="space-y-5">
      <PageHeading
        title="What happened here?"
        description="Pick a place and a time. You get a plain-language summary built only from the dataset, then see it on a 3D map."
      />
      <DataNotices />
      <DataGate>{({ datasetId }) => <StoryBody key={datasetId} datasetId={datasetId} />}</DataGate>
    </div>
  );
}
